// Turns the icon table into the two files the rest of the project reads:
//   tools/art/icons.json      what the atlas builder (tools/art/icons.html) draws, in atlas order
//   public/js/icon-map.js     which emoji become which icon (the game swaps them at runtime)
// Usage: node tools/art/build-icons.mjs [path/to/a/text/file/of/emoji/to/check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ICONS } from './icon-table.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');

// emoji are compared without the invisible "make it an emoji" marker
const norm = (e) => e.replace(/️/g, '');

const spec = [];
const map = {};
for (const [name, { emoji = [], ...source }] of Object.entries(ICONS)) {
  spec.push({ name, ...source });
  for (const e of emoji) {
    const k = norm(e);
    if (map[k] && map[k] !== name) console.warn(`emoji ${e} is mapped twice: ${map[k]} and ${name}`);
    map[k] = name;
  }
}
fs.writeFileSync(path.join(HERE, 'icons.json'), JSON.stringify(spec));

const entries = Object.entries(map).sort((a, b) => b[0].length - a[0].length || a[0].localeCompare(b[0]));
const body = entries.map(([e, n]) => `  ${JSON.stringify(e)}: ${JSON.stringify(n)},`).join('\n');
const COLS = 16; // keep in step with the cols the atlas page is run with (see tools/art/icons.html)
const index = Object.fromEntries(spec.map((s, i) => [s.name, i]));
fs.writeFileSync(
  path.join(ROOT, 'public/js/icon-map.js'),
  `// GENERATED by tools/art/build-icons.mjs from tools/art/icon-table.mjs: do not edit by hand.\n// ATLAS says where each icon sits in public/assets/icons/atlas.webp; EMOJI_ICON says which emoji are drawn as\n// which icon (see icons.js).\nexport const ATLAS = { cols: ${COLS}, rows: ${Math.ceil(spec.length / COLS)}, size: 48, icons: ${JSON.stringify(index)} };\n\nexport const EMOJI_ICON = {\n${body}\n};\n`,
);
// where each icon sits, as CSS variables (for rules that cannot use an element: ::before and ::after)
const vars = spec.map((s, i) => `  --ix-${s.name}: ${i % COLS}; --iy-${s.name}: ${Math.floor(i / COLS)};`).join('\n');
fs.writeFileSync(path.join(ROOT, 'public/css/icon-index.css'), `/* GENERATED by tools/art/build-icons.mjs: do not edit by hand. */\n:root {\n${vars}\n}\n`);
console.log(`${spec.length} icons, ${entries.length} emoji mapped`);

// optional: which emoji from a list ("emoji name count" per line) have no icon yet?
const check = process.argv[2];
if (check) {
  const missing = [];
  for (const line of fs.readFileSync(check, 'utf8').split('\n')) {
    const e = line.split(' ')[0];
    if (!e) continue;
    const n = norm(e).replace(/‍/g, '‍');
    if (!map[n] && !map[n.replace(/‍.*$/u, '')]) missing.push(line);
  }
  console.log(`unmapped (${missing.length}):\n${missing.join('\n')}`);
}
